// Generates worker/prompts.js from play/app.js so the Worker asks Gemini the exact
// questions the game was tuned with, and the two can never drift apart silently.
//
//   node worker/build-prompts.mjs          → rewrite worker/prompts.js
//   node worker/build-prompts.mjs --check  → exit 1 if prompts.js is out of date
//
// Run it (then `npx wrangler deploy`) whenever an item, a category or an aiPrompt
// in play/app.js changes. The Worker rejects any item it does not know.

import vm from 'node:vm';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const OUT = path.join(HERE, 'prompts.js');

// Minimal browser stand-in: app.js only needs to get as far as defining CATEGORIES.
function noopEl() {
  return { style: {}, classList: { add() {}, remove() {}, toggle() {} }, setAttribute() {}, removeAttribute() {},
    appendChild() {}, removeChild() {}, remove() {}, addEventListener() {}, querySelector() { return null; },
    querySelectorAll() { return []; }, insertAdjacentHTML() {}, focus() {}, getContext() { return {}; },
    innerHTML: '', textContent: '' };
}
const store = {};
const doc = { addEventListener() {}, getElementById() { return null; }, querySelector() { return null; },
  querySelectorAll() { return []; }, createElement() { return noopEl(); }, head: noopEl(), body: noopEl() };
const ctx = { console, JSON, Math, Date, Object, Array, String, Number, Boolean, RegExp, Error, parseInt, parseFloat,
  isNaN, Set, Map, Promise, Symbol, encodeURIComponent, decodeURIComponent,
  setTimeout() {}, clearTimeout() {}, setInterval() {}, clearInterval() {}, addEventListener() {}, removeEventListener() {},
  document: doc,
  localStorage: { getItem(k) { return store[k] == null ? null : store[k]; }, setItem(k, v) { store[k] = String(v); }, removeItem(k) { delete store[k]; } },
  navigator: { onLine: true }, location: { hash: '', search: '', pathname: '/', replace() {} }, history: { replaceState() {} },
  requestAnimationFrame() {}, matchMedia() { return { matches: false }; }, fetch() { return Promise.resolve({}); },
  AudioContext: function () { return { state: 'running', resume() {}, createBuffer() { return {}; },
    createBufferSource() { return { connect() {}, start() {} }; }, destination: {} }; } };
ctx.window = ctx; ctx.self = ctx; ctx.webkitAudioContext = ctx.AudioContext;
vm.createContext(ctx);
for (const f of ['play/content/translations/languages-config.js', 'play/content/translations/all-translations.js', 'play/app.js']) {
  vm.runInContext(fs.readFileSync(path.join(REPO, f), 'utf8'), ctx, { filename: f });
}
const CATEGORIES = vm.runInContext('CATEGORIES', ctx);

const SENTINEL = '\u0001ITEM\u0001';
const TAIL = / On the second line, describe what you see[^.]*\.$/;
const fill = (tpl, name) => tpl.split('{n}').join(name);

const items = new Set();
for (const cat of Object.values(CATEGORIES)) for (const it of cat.items || []) items.add(it.name);

// Story Quests pair items with categories; every pair must be answerable.
const storySrc = fs.readFileSync(path.join(REPO, 'play/storyline-mode.js'), 'utf8');
for (const m of storySrc.matchAll(/item:\s*'([^']+)',\s*category:\s*'([^']+)'/g)) {
  if (!CATEGORIES[m[2]]) throw new Error('Story step uses unknown category: ' + m[2]);
  items.add(m[1]);
}

const templates = {}, overrides = {};
for (const [id, cat] of Object.entries(CATEGORIES)) {
  const tpl = cat.aiPrompt(SENTINEL).split(SENTINEL).join('{n}');
  if (!tpl.includes('{n}')) throw new Error('Category ' + id + ' prompt does not use the item name');
  if (!TAIL.test(tpl)) throw new Error('Category ' + id + ' prompt lost its "second line" ending; update TAIL here and in worker.js');
  templates[id] = tpl;
  for (const name of items) {
    const real = cat.aiPrompt(name);
    if (real !== fill(tpl, name)) {
      if (!TAIL.test(real)) throw new Error('Override ' + id + '/' + name + ' lost its "second line" ending');
      (overrides[id] = overrides[id] || {})[name] = real;
    }
  }
}

const out = '// GENERATED by worker/build-prompts.mjs from play/app.js. Do not edit by hand.\n'
  + '// Re-run the generator and redeploy the Worker after changing items or prompts.\n\n'
  + 'export const TEMPLATES = ' + JSON.stringify(templates, null, 2) + ';\n\n'
  + 'export const OVERRIDES = ' + JSON.stringify(overrides, null, 2) + ';\n\n'
  + 'export const ITEMS = ' + JSON.stringify([...items].sort(), null, 2) + ';\n';

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) { console.error('worker/prompts.js is OUT OF DATE. Run: node worker/build-prompts.mjs, then redeploy the Worker.'); process.exit(1); }
  console.log('worker/prompts.js is up to date (' + Object.keys(templates).length + ' categories, ' + items.size + ' items).');
} else {
  fs.writeFileSync(OUT, out);
  console.log('Wrote worker/prompts.js: ' + Object.keys(templates).length + ' categories, ' + items.size + ' items, '
    + Object.values(overrides).reduce((n, o) => n + Object.keys(o).length, 0) + ' overrides.');
}
